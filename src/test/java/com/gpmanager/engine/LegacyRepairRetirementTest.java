package com.gpmanager;

import static org.junit.Assert.*;

import com.google.gson.Gson;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.List;
import org.junit.Test;

/** Retiring migrations preserves repaired wire data and does not rewrite untouched history. */
public class LegacyRepairRetirementTest {
    static final long START = 1_800_000_000_000L;

    static Engine engine() {
        JsonCodec.bind(new Gson());
        Engine engine = TargetFreshStartTest.engine();
        engine.ensureSession(START);
        return engine;
    }

    @Test public void alreadyRepairedSaveKeepsEveryReceiptAndItsValues() throws Exception {
        Engine engine = engine();
        try (var stream = getClass().getResourceAsStream("/com/gpmanager/repaired-legacy.json")) {
            assertNotNull("synthetic fixture was generated by the pre-retirement engine", stream);
            try (var reader = new InputStreamReader(stream, StandardCharsets.UTF_8)) {
                engine.restore(new Gson().fromJson(reader, SavedState.class), START + 10000);
            }
        }
        String before = new Gson().toJson(engine.session().transactions());
        long net = engine.session().metrics(START + 10001).net;
        engine.recheck();
        assertEquals(before, new Gson().toJson(engine.session().transactions()));
        assertEquals(net, engine.session().metrics(START + 10002).net);
        assertEquals(3, engine.session().transactions().size());
        assertEquals(0, engine.session().transactions().stream().filter(ReviewRules::needsReview).count());
        assertEquals(1, engine.session().transactions().stream().filter(row -> row.action() == ActionKind.CAST).count());
    }

    @Test public void anUntouchedOldSpellBundleIsNotSplitOrReclassified() {
        Engine engine = engine();
        Transaction old = new Transaction(START, TransactionType.CONSUMPTION, Context.GENERIC, "", "Magic", true,
                List.of(new Flow(562, "Chaos rune", -4, 105, -420),
                        new Flow(560, "Death rune", -2, 191, -382), new Flow(555, "Water rune", -4, 4, -16)),
                Confidence.LIKELY, "Historical receipt", null);
        engine.session().addTransaction(old, 2000, false);
        String before = new Gson().toJson(old);
        engine.recheck();
        assertEquals(before, new Gson().toJson(old));
        assertEquals(1, engine.session().transactions().size());
    }
}
